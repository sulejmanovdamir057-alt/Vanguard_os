//! Общая библиотека Vanguard OS: протокол IPC ядра и разделяемые типы.
//!
//! Из этой библиотеки собираются три процесса:
//! - `vanguard_core`  — ядро: нейронный шелл, телеметрия, исполнитель, компилятор
//!   (`core::main` слушает TCP и обслуживает [`ipc::Request`]);
//! - `vanguard_os`    — оболочка: egui-рендер, рисует [`ai_core::AiEvent`] потоком;
//! - `vanguard_ai`    — ИИ-помощник (следующий этап).
//!
//! Общие типы лежат здесь, чтобы протокол не разъехался между процессами:
//! бинарники только тонко заворачивают эти же модули.

/// Протокол IPC: JSON-строки поверх TCP на локалхосте. Единственный источник
/// правды о формате обмена между ядром и оболочкой/помощником.
pub mod ipc;

/// Конфигурация бэкенда и стриминг ответа ИИ. Остаётся в оболочке и помощнике:
/// запрос к Ollama и SSE-разбор не тяжёлые, а заморозка UI ими не грозит.
pub mod ai_core;

/// Движок ядра: шелл слеш-команд, исполнитель скриптов, телеметрия, формат
/// приложений. Эти модули нужны и оболочке (типы `ShellAction`, `AiEvent`,
/// `SystemMetrics`, `AppInfo`), поэтому живут в lib, а процесс ядра их
/// только обслуживает.
pub mod core {
    pub mod shell;
    pub mod executor;
    pub mod telemetry;
    pub mod apps;
}
