// Пример приложения формата apps/<id> на Go: ядро собирает этот файл через
// `go build -o %TEMP%` и запускает отдельным процессом. Однофайловому входу
// go.mod не нужен; сам Go SDK должен быть в PATH (`go version` в терминале).
//
// Консольное приложение: оболочка без консоли выделит окно процессу сама.
// stdin закрыт (Stdio::null), поэтому пауза по Enter не работала бы —
// держим окно таймером, как у любого короткого консольного демо.
package main

import (
	"fmt"
	"time"
)

func main() {
	fmt.Println("Привет из Go!")
	fmt.Println("Это консольное приложение Vanguard OS, собранное через go build.")
	fmt.Println("Окно закроется само через 10 секунд...")
	time.Sleep(10 * time.Second)
}
